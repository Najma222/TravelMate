"""Flask CLI commands: ``seed-discover``, ``seed-demo``, ``simulate-callback``."""
from __future__ import annotations

import json
from datetime import timedelta
from decimal import Decimal

import click
from flask import Flask, current_app


def register_cli(app: Flask) -> None:
    @app.cli.command("seed-discover")
    @click.option("--file", "path", default=None, help="Alternative JSON seed file.")
    def seed_discover(path):
        """Upsert discover destinations from seed/discover_destinations.json (idempotent)."""
        from app.services import discover_service

        n, total = discover_service.seed_destinations(path)
        click.echo(f"Upserted {n} destinations ({total} in table).")

    @app.cli.command("seed-demo")
    @click.option("--email", default="demo@travelmate.local")
    @click.option("--password", default="DemoPass123")
    def seed_demo(email, password):
        """Create a demo user with sample trips (development/testing only)."""
        if not current_app.config.get("ALLOW_DEMO_SEED"):
            raise click.ClickException("seed-demo is disabled in this environment (production).")
        from app.extensions import db
        from app.models import User
        from app.services import auth_service, booking_service, expense_service, trip_service
        from app.utils.dates import today

        email = email.strip().lower()
        if db.session.query(User).filter_by(email=email).first():
            click.echo(f"Demo user {email} already exists; nothing to do.")
            return
        user = auth_service.register({"name": "Demo Traveller", "email": email, "password": password})
        t0 = today()
        goa = trip_service.create_trip(user.id, {
            "origin": "Mumbai", "destination": "Goa",
            "start_date": t0 + timedelta(days=20), "end_date": t0 + timedelta(days=24),
            "traveller_count": 2, "budget": Decimal("45000.00"),
            "currency": "INR", "preferences": "Beaches, seafood, relaxed pace",
            "transport_preference": "train", "accommodation_preference": "hotel",
        })
        trip_service.create_trip(user.id, {
            "origin": "Delhi", "destination": "Manali",
            "start_date": t0 + timedelta(days=45), "end_date": t0 + timedelta(days=50),
            "traveller_count": 3, "budget": Decimal("60000.00"),
            "currency": "INR", "preferences": "Mountains, trekking",
            "transport_preference": "bus", "accommodation_preference": "homestay",
        })
        expense_service.create_expense(user.id, goa.id, {
            "category": "food", "description": "Food (estimate)", "amount": Decimal("8000.00"),
            "is_confirmed": False})
        booking_service.create_booking(user.id, goa.id, {
            "booking_type": "train", "provider": "Indian Railways", "booking_reference": "PNR1234567",
            "amount": Decimal("3200.00"), "status": "Confirmed",
            "from_location": "Mumbai CSMT", "to_location": "Madgaon"})
        click.echo(f"Created demo user {email} with 2 trips.")

    @app.cli.command("simulate-callback")
    @click.option("--trip-id", type=int, required=True)
    @click.option("--file", "path", default=None,
                  help="JSON payload file. generation_id is filled in from the trip if absent.")
    @click.option("--fail", is_flag=True, help="Simulate an n8n failure result.")
    def simulate_callback(trip_id, path, fail):
        """Run the REAL callback service for a Processing trip (development only)."""
        if not current_app.config.get("ALLOW_DEMO_SEED"):
            raise click.ClickException("simulate-callback is disabled in production.")
        from app.extensions import db
        from app.models import Trip
        from app.services import callback_service, trip_rules
        from app.utils.validators import parse_json_bytes

        trip = db.session.get(Trip, trip_id)
        if trip is None:
            raise click.ClickException("Trip not found")
        if path:
            with open(path, "rb") as fh:
                payload = parse_json_bytes(fh.read())
        elif fail:
            payload = {"status": "Failed", "error_message": "Simulated failure"}
        else:
            days = trip_rules.duration_days(trip.start_date, trip.end_date)
            payload = {
                "status": "Completed",
                "itinerary": [
                    {"day_number": d, "activity_name": f"[SIMULATED] Activity {d}.{i}",
                     "description": "Development placeholder generated by simulate-callback.",
                     "start_time": f"{9 + 3 * i:02d}:00", "end_time": f"{11 + 3 * i:02d}:00",
                     "estimated_cost": "0"}
                    for d in range(1, days + 1) for i in range(2)
                ],
                "days": [{"day_number": d, "title": f"Day {d}"} for d in range(1, days + 1)],
                "expenses": [],
                "stops": [],
            }
        payload.setdefault("generation_id", str(trip.generation_id) if trip.generation_id else None)
        db.session.rollback()
        result = callback_service.process_callback(trip_id, payload)
        click.echo(json.dumps(result.body, indent=2, default=str))
